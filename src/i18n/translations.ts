// #307); STYLE_GUIDE.md's "UI text / i18n" section lists the few deliberate
// exceptions and the convention for adding new keys.
//
// "common.*" keys are reused verbatim across call sites -- one shared key
// per distinct piece of UI text, not a new key per JSX location.
